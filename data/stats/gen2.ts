// Helper to convert 6-stat format (standard) to 3-stat format (simplified)
// Usage: s(HP, Atk, Def, SpA, SpD, Spe)
const s = (hp: number, atk: number, def: number, spa: number, spd: number, spe: number): PokemonStats => ({
    hp: hp,
    atk: Math.round((atk + spa) / 2),
    def: Math.round((def + spd) / 2 + (spe / 20))
});

